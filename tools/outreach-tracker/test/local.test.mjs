import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createLocalServer } from '../server.mjs';

test('local service protects pairing, validates drafts, persists state and never calls a send API', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'jobmax-local-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const packageDir = join(dir, 'packages'); await mkdir(packageDir);
  await writeFile(join(packageDir, 'batch.json'), JSON.stringify({ contacts: [{ id: 'test-person', email: { address: 'person@example.com' }, emailDraft: { subject: 'Test subject' }, sendBlockers: [] }] }));
  const calls = [];
  const fetcher = async (url, options) => { calls.push({ url, body: options.body }); return Response.json({ healthy: true, coverageHealthy: true, reportedOpens: 0 }); };
  const { server, token } = await createLocalServer({ dataDir: join(dir, 'data'), packageDir, fetcher });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const request = (path, body, headers = {}) => fetch(`${origin}/api/${path}`, { method: body ? 'POST' : 'GET', headers: { 'X-JobMax-Token': token, 'Content-Type': 'application/json', ...headers }, body: body ? JSON.stringify(body) : undefined });
  assert.equal((await request('state', null, { Origin: 'https://evil.example' })).status, 403);
  assert.equal((await request('state', null, { 'X-JobMax-Token': 'wrong' })).status, 401);
  assert.equal((await request('bootstrap', null, { Origin: `chrome-extension://${'a'.repeat(32)}` })).status, 403);
  assert.equal((await request('bootstrap', null, { 'Sec-Fetch-Site': 'cross-site' })).status, 403);
  assert.equal((await request('config', { endpoint: 'http://not-https.example', adminToken: 'b'.repeat(64) })).status, 400);
  assert.equal((await request('config', { endpoint: 'https://collector.example', adminToken: 'b'.repeat(64) })).status, 200);
  assert.equal((await request('prepare', { packageId: 'test-person', recipient: 'wrong@example.com', subject: 'Test subject' })).status, 400);
  const prepared = await (await request('prepare', { packageId: 'test-person', recipient: 'person@example.com', subject: 'Test subject' })).json();
  assert.match(prepared.id, /^[a-f0-9]{48}$/);
  assert.equal((await request('event', { packageId: 'test-person', kind: 'sent' })).status, 400);
  assert.equal((await request('event', { packageId: 'test-person', kind: 'sent', confirmed: true })).status, 200);
  assert.equal((await request('event', { packageId: 'test-person', kind: 'sent', confirmed: true })).status, 400);
  assert.equal((await request('prepare', { packageId: 'test-person', recipient: 'person@example.com', subject: 'Test subject' })).status, 400);
  assert.equal((await request('event', { packageId: 'test-person', kind: 'followup-sent', confirmed: true })).status, 400);
  assert.equal((await request('config', { endpoint: 'https://other.example', adminToken: 'b'.repeat(64) })).status, 400);
  const state = await (await request('state')).json();
  assert.ok(state.contacts[0].message.sentAt);
  assert.equal(JSON.stringify(state).includes('b'.repeat(64)), false);
  assert.ok(calls.every(call => new URL(call.url).pathname.startsWith('/admin/')));
});

test('eligible follow-up has a separate pixel and stops after one follow-up', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'jobmax-followup-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const packageDir = join(dir, 'packages'); await mkdir(packageDir);
  await writeFile(join(packageDir, 'batch.json'), JSON.stringify({ contacts: [{ id: 'test-person', email: { address: 'person@example.com' }, emailDraft: { subject: 'Test' }, sendBlockers: [] }] }));
  const calls = [];
  let opens = 0;
  const fetcher = async (url, options) => {
    calls.push({ url, body: options.body });
    return Response.json({ healthy: true, coverageHealthy: true, reportedOpens: opens });
  };
  const { server, token } = await createLocalServer({ dataDir: join(dir, 'data'), packageDir, fetcher });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const request = (path, body) => fetch(`http://127.0.0.1:${server.address().port}/api/${path}`, { method: 'POST', headers: { 'X-JobMax-Token': token, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  await request('config', { endpoint: 'https://collector.example', adminToken: 'b'.repeat(64) });
  const draft = { packageId: 'test-person', recipient: 'person@example.com', subject: 'Test' };
  const initial = await (await request('prepare', draft)).json();
  await request('event', { packageId: draft.packageId, kind: 'sent', confirmed: true, at: new Date(Date.now() - 30 * 86400000).toISOString() });
  const followup = { ...draft, phase: 'followup', subject: 'Re: Test' };
  opens = 1;
  assert.equal((await request('prepare', followup)).status, 400);
  opens = 0;
  const prepared = await (await request('prepare', followup)).json();
  assert.match(prepared.id, /^[a-f0-9]{48}$/);
  assert.notEqual(prepared.id, initial.id);
  assert.equal((await request('arm', { trackingId: prepared.id })).status, 200);
  assert.equal((await request('event', { packageId: draft.packageId, kind: 'followup-sent', confirmed: true })).status, 200);
  assert.ok(calls.some(call => call.url.endsWith(`/${prepared.id}/sent`)));
  assert.equal((await request('prepare', followup)).status, 400);
});
